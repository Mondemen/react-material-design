import React, { useCallback, useMemo, type ComponentPropsWithoutRef, type ElementType } from "react";
import type { DefaultThemeComponentType } from "../Theme/types";
import { useTheme } from "@components/Theme/Theme";

export type PolymorphicComponent<Name extends string, As extends ElementType | undefined, Default extends ElementType, Props = {}> =
(
	/*if*/ NonNullable<As> extends (props: any) => React.ReactNode | Promise<React.ReactNode> ?
		Omit<ComponentPropsWithoutRef<NonNullable<As>>, keyof Props>
	/*else if*/ : NonNullable<As> extends keyof React.JSX.IntrinsicElements ?
		Omit<ComponentPropsWithoutRef<NonNullable<As>>, keyof Props>
	/*else*/ :
		Omit<ComponentPropsWithoutRef<DefaultThemeComponentType<Name, Default>>, keyof Props>
) & {as?: As} & React.PropsWithChildren<Props>;

// export const usePolymorphicIsToApply = (props: Record<PropertyKey, any>, exclude: PropertyKey[]) => useMemo(() => Object.keys(props).some(prop => !exclude.includes(prop) && !HtmlProps.includes(prop)), [exclude, props]);
// export const useAnchorIsToApply = (props: Record<PropertyKey, any>) => useMemo(() => Object.keys(props).some(prop => AnchorProps.includes(prop)), [props]);

export interface PolymorphicProps
{
	name: string,
	props: Record<PropertyKey, any>,
	as: ElementType | undefined,
	base?: ElementType,
	// default: ElementType,
	// isDefault: boolean,
	// extraProps?: Record<PropertyKey, any>,
	ref?: React.Ref<HTMLElement>,
	excludePropsName: string[],
	disabled?: boolean
}

export default function Polymorphic(props: React.PropsWithChildren<PolymorphicProps>)
{
	const {base: Base = "div"} = props;
	const excludePropsName = useMemo(() => ["as", "children", "orderedCollectionName", ...props.excludePropsName], [props.excludePropsName]);
	const ContextType = useTheme()?.config.componentTypes?.[props.name];
	const ref = useCallback<React.RefCallback<HTMLElement>>(ref =>
	{
		const refObject = props.ref;

		if (refObject)
		{
			if (typeof refObject === "function")
				return (refObject(ref));
			refObject.current = ref;
			return (() => {refObject.current = null});
		}
	}, [props]);
	// const isPolymorphicIsToApply = usePolymorphicIsToApply(props.props, excludePropsName);
	const nativeProps = useMemo(() =>
	{
		const result: React.ComponentProps<any> = {...props.props};

		excludePropsName.forEach(prop => delete result[prop])
		return (result);
	}, [excludePropsName, props.props]);

	if (!props.disabled)
	{
		if (props.as)
			return (<props.as ref={ref} {...nativeProps}>{props.children}</props.as>);
		else if (ContextType/*  && isPolymorphicIsToApply */)
			return (<ContextType ref={ref} {...nativeProps}>{props.children}</ContextType>);
	}
	// else if (props.isDefault)
	// 	return (<props.default ref={ref} {...nativeProps} disabled={props.disabled}>{props.children}</props.default>);
	return (<Base ref={ref} {...nativeProps} disabled={props.disabled}>{props.children}</Base>);
}

